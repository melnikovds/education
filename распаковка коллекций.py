# Распаковка со звёздочкой (*) в Python — это способ присвоить одной переменной сразу
# несколько элементов из списка, кортежа или другой коллекции.
# Это незаменимо, когда точное количество элементов заранее неизвестно.

# Оператор * собирает все «лишние» элементы,
# которые не поместились в обычные переменные, в новый список.

# Сбор элементов в конце
a, b, *c = [1, 2, 3, 4, 5]
# a = 1
# b = 2
# c = [3, 4, 5] (все оставшиеся элементы)

# Сбор элементов в середине
# a, *b, c = [1, 2, 3, 4, 5]
# a = 1
# b = [2, 3, 4] (всё, что между первым и последним)
# c = 5

# Сбор элементов в начале
# *a, b, c = [1, 2, 3, 4, 5]
# # a = [1, 2, 3]
# # b = 4
# # c = 5

# Важные правилаТолько одна звёздочка:
# В левой части выражения нельзя использовать более одной переменной со звёздочкой
# (например, a, *b, *c = [1, 2, 3] вызовет ошибку SyntaxError).
# Всегда возвращает список: Даже если справа был кортеж или строка,
# переменная со звёздочкой всегда станет списком (list).
# Если элементов для неё не осталось, она вернет пустой список [].


# Распаковка с двумя звёздочками (**) в Python используется для работы со словарями (dict).
# Она позволяет разворачивать пары «ключ-значение» и чаще всего применяется
# в двух ситуациях: для объединения словарей и для передачи аргументов в функции.

# С помощью ** можно легко перенести все элементы одного или нескольких словарей в новый.
dict1 = {'a': 1, 'b': 2}
dict2 = {'c': 3, 'd': 4}

# Объединяем в новый словарь
combined = {**dict1, **dict2}
# Результат: {'a': 1, 'b': 2, 'c': 3, 'd': 4}

# Обновление значений при конфликте ключей:
# Если в объединяемых словарях есть одинаковые ключи,
# то значение из словаря, который указан правее, перезапишет предыдущее.
base_config = {'theme': 'light', 'status': 'active'}
user_config = {'theme': 'dark'}

final_config = {**base_config, **user_config}
# Результат: {'theme': 'dark', 'status': 'active'}

# Поверхностное копирование
original = {'x': 10}
copy_of_original = {**original}