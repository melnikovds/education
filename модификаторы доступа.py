# Public (публичный)
#
# Доступен откуда угодно
# Без подчёркивания
# Самый открытый уровень доступа

class Student:
    name = "Faizu"

obj = Student()
print(obj.name)


# Protected (защищённый)
#
# Доступен внутри класса и в дочерних классах
# Строгого ограничения в Python нет (это соглашение)
# Обозначается одним подчёркиванием _age
# Средний уровень «защиты» (предупреждение)

class Student:
    _age = 20

class Child(Student):
    def show(self):
        print(self._age)


# Private (приватный)
#
# Доступен только внутри класса
# Обозначается двойным подчёркиванием __marks
# Самый закрытый уровень доступа

class Student:
    __marks = 90

    def show(self):
        print(self.__marks)


# Сравнительная таблица
# | Тип       | Символ   | Доступ снаружи           | В дочернем классе | Уровень |
# | --------- | -------- | ------------------------ | ----------------- | ------- |
# | Public    | нет      | ✅ Да                    | ✅ Да             | Низкий  |
# | Protected | `_name`  | ⚠️ Да (не рекомендуется) | ✅ Да             | Средний |
# | Private   | `__name` | ❌ Нет                   | ❌ Нет*           | Высокий |

# *Технически доступ возможен через name mangling:
# _ClassName__name


# Примеры из жизни
# Public → ник в Instagram
# Protected → замок на двери
# Private → PIN-код банкомата
