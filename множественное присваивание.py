# Множественное присваивание в Python позволяет записать значения
# в несколько переменных в одной строке кода
a, b, c = 5, 3, 1  # a = 5, b = 3, c = 1
# Обмен значений двух переменных без использования третьей временной переменной
# a, b = 1, 2
# a, b = b, a  # теперь a = 2, b = 1

# Распаковка коллекций (списков или строк)
x, y, z = "123"  # x = '1', y = '2', z = '3'








